    println(s"reverse $l")
    println(s"binarySearch with reverseOrder 7=${ju.Collections.binarySearch(l, Integer.valueOf(7), ju.Collections.reverseOrder[Integer]())}")
    ju.Collections.sort(l, ju.Collections.reverseOrder[Integer]())
    println(s"sort reverseOrder $l")
    ju.Collections.swap(l, 0, 6)
    println(s"swap $l")
    ju.Collections.rotate(l, 2)
    println(s"rotate 2 $l")
    ju.Collections.rotate(l, -3)
    println(s"rotate -3 $l")
