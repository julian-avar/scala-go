  def base64(): Unit =
    section("Base64")
    val inputs = List("", "f", "fo", "foo", "foob", "fooba", "foobar", "ÿþý?>", "hello world")
    for s <- inputs do
      val bytes = s.getBytes("ISO-8859-1")
      val basic = ju.Base64.getEncoder.encodeToString(bytes)
      val url = ju.Base64.getUrlEncoder.encodeToString(bytes)
      val nopad = ju.Base64.getEncoder.withoutPadding.encodeToString(bytes)
      val back = new String(ju.Base64.getDecoder.decode(basic), "ISO-8859-1")
      println(s"'$s' basic=$basic url=$url nopad=$nopad roundtrip=${back == s}")
