    val uc = ju.Collections.unmodifiableCollection(strList("c"))
    val usm = ju.Collections.unmodifiableSortedMap(base)
    base.put("y", 2)
    println(s"unmodifiable views $um $us $uc firstKey=${usm.firstKey} lastKey=${usm.lastKey}")
    attempt("unmodifiableMap remove")(um.remove("x"))
    attempt("unmodifiableSet add")(us.add("z"))
    attempt("unmodifiableMap entry setValue")(um.entrySet.iterator.next().setValue(5))
    attempt("unmodifiableCollection clear")(uc.clear())
    val sync = ju.Collections.synchronizedList(new ju.ArrayList[String]())
    sync.add("s1"); sync.add("s2")
    sync.synchronized { sync.add("s3") }
    println(s"synchronizedList $sync size=${sync.size} get=${sync.get(1)}")
    val syncMap = ju.Collections.synchronizedMap(new ju.TreeMap[String, Integer]())
    syncMap.put("b", 2); syncMap.put("a", 1)
    println(s"synchronizedMap $syncMap")
    val ro = ju.Collections.reverseOrder[String]()
