    println(s"mime custom $mime2")
    println(s"mime decode roundtrip ${ju.Arrays.equals(ju.Base64.getMimeDecoder.decode(mime), bin)}")
    println(s"url decode ${ju.Arrays.equals(ju.Base64.getUrlDecoder.decode(ju.Base64.getUrlEncoder.encodeToString(bin)), bin)}")
    println(s"decode without padding ${new String(ju.Base64.getDecoder.decode("Zm9vYg"))}")
    println(s"mime decoder ignores junk ${new String(ju.Base64.getMimeDecoder.decode("Zm9v\r\nYmFy!!"))}")
