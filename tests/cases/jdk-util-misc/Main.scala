    none.ifPresent(v => println(s"never $v"))
    some.ifPresentOrElse(v => println(s"ifPresentOrElse present $v"), () => println("absent"))
    none.ifPresentOrElse(v => println(s"present $v"), () => println("ifPresentOrElse absent"))
