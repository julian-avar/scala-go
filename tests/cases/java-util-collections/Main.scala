    println(s"contains bb=${bylen.contains("bb")} remove(bb)=${bylen.remove("bb")}")
    val out3 = new StringBuilder
    while !bylen.isEmpty do out3.append(bylen.poll()).append(' ')
    println(s"by length ${out3.toString.trim}")
