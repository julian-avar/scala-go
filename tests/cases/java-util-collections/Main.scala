  def failFast(): Unit =
    section("ConcurrentModificationException")
    val al = new ju.ArrayList[Integer](ju.List.of[Integer](1, 2, 3, 4))
    attempt("ArrayList add during iteration") {
      val it = al.iterator
      while it.hasNext do if it.next() == 2 then al.add(5)
    }
    attempt("ArrayList forEach modify")(al.forEach(x => if x == 1 then al.remove(Integer.valueOf(4))))
    val hm = new ju.HashMap[String, Integer]()
    for i <- 0 until 5 do hm.put(s"k$i", i)
    attempt("HashMap put during keySet iteration") {
      val it = hm.keySet.iterator
      while it.hasNext do if it.next() == "k1" then hm.put("new", 9)
    }
    attempt("HashMap remove during entrySet iteration") {
      val it = hm.entrySet.iterator
      it.next()
      hm.remove("k3")
      it.next()
    }
    attempt("HashMap value overwrite during iteration is fine") {
      val it = hm.keySet.iterator
      var n = 0
      while it.hasNext do
        hm.put(it.next(), 0); n += 1
      n
    }
    val tm = new ju.TreeMap[Integer, Integer]()
    for i <- 0 until 5 do tm.put(i, i)
    attempt("TreeMap put during iteration") {
      val it = tm.keySet.iterator
