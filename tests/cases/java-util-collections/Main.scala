  def iterators(): Unit =
    section("Iterator / ListIterator")
    val l = new ju.ArrayList[String](ju.List.of("a", "b", "c", "d"))
    val li = l.listIterator()
    while li.hasNext do
      val i = li.nextIndex
      val s = li.next()
      if s == "b" then li.remove()
      else if s == "c" then li.set("C")
      else if s == "d" then li.add("e")
      else li.add(s"$s$i")
    println(s"after forward pass $l")
    val back = new StringBuilder
    while li.hasPrevious do
      back.append(li.previousIndex).append(':').append(li.previous()).append(' ')
    println(s"backward ${back.toString.trim}")
    val li2 = l.listIterator(2)
    println(s"listIterator(2) next=${li2.next()} previous=${li2.previous()} previous=${li2.previous()}")
    li2.set("SET")
    println(s"set after previous $l")
    attempt("remove without next")(l.iterator.remove())
    val ll = new ju.LinkedList[Integer](ju.List.of[Integer](1, 2, 3, 4, 5))
    val lli = ll.listIterator(ll.size)
    while lli.hasPrevious do
      val x = lli.previous()
      if x % 2 == 1 then lli.remove()
      else
        lli.add(x * 100)
        print(s"skip ${lli.previous()} ")
    println(s"linkedlist reverse edit $ll")
    attempt("next past end")(ju.List.of[Integer](1).iterator.tap(_.next()).next())
    val ent = ju.Map.entry[String, Integer]("k", 1)
    println(s"Map.entry $ent key=${ent.getKey} value=${ent.getValue}")
    val se = new ju.AbstractMap.SimpleEntry[String, Integer]("s", 2)
    se.setValue(5)
    println(s"SimpleEntry $se equals=${se.equals(ju.Map.entry[String, Integer]("s", 5))} hash=${se.hashCode == ju.Map.entry[String, Integer]("s", 5).hashCode}")
    attempt("Map.entry setValue")(ent.setValue(3))
    val sorted = new ju.ArrayList[ju.Map.Entry[String, Integer]](ju.List.of(ju.Map.entry[String, Integer]("b", 2), ju.Map.entry[String, Integer]("a", 3), ju.Map.entry[String, Integer]("c", 1)))
    sorted.sort(ju.Map.Entry.comparingByValue[String, Integer]())
    println(s"comparingByValue $sorted")
    sorted.sort(ju.Map.Entry.comparingByKey[String, Integer]())
    println(s"comparingByKey $sorted")

