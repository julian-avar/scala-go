    val out2 = new StringBuilder
    while !maxq.isEmpty do out2.append(maxq.poll()).append(' ')
    println(s"reverse polled ${out2.toString.trim}")
    val bylen = new ju.PriorityQueue[String](11, (a: String, b: String) => Integer.compare(a.length, b.length) match
      case 0 => a.compareTo(b)
