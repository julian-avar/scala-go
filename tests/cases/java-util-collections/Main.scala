  def priorityQueue(): Unit =
    section("PriorityQueue")
    val pq = new ju.PriorityQueue[Integer]()
    for x <- List(5, 1, 8, 3, 9, 2, 7, 3, 0, 6) do pq.add(x)
    println(s"size=${pq.size} peek=${pq.peek}")
