import scala.collection.immutable.*

/** scala.collection.immutable: sequences, sets, maps, ranges and their operations. Hash-based
  * collections are sorted before printing: their iteration order is not part of the API. */
object Main:
  def section(name: String): Unit = println(s"-- $name")

  def main(args: Array[String]): Unit =
    lists()
    seqOps()
    vectors()
    ranges()
    sets()
    maps()
    sortedCollections()
    queues()
    arraySeqs()
    bitSets()

  def lists(): Unit =
    section("List")
    val xs = List(3, 1, 4, 1, 5, 9, 2, 6)
    println(0 :: xs)
    println(xs ::: List(7, 8))
    println(List(1, 2) ++ Vector(3) :+ 4)
    println(Nil)
    println(List.empty[Int].headOption)
    println(xs match { case a :: b :: rest => s"$a $b ${rest.size}"; case _ => "short" })
    println(List.fill(3)("x"))
    println(List.tabulate(4)(i => i * i))
    println(List.iterate(1, 5)(_ * 3))
    println(List.unfold(10)(n => if n == 0 then None else Some((n, n / 2))))
    println(List.range(0, 10, 3))
    println(List(List(1, 2), List(3), Nil).flatten)
    println(xs.reverse_:::(List(0, -1)))
    println(s"${xs.init} ${xs.last}")
    println(s"${xs.drop(5)} ${xs.dropRight(5)} ${xs.takeRight(2)}")
    println(try List.empty[Int].head catch case e: NoSuchElementException => e.getMessage)

  def seqOps(): Unit =
    section("Seq operations")
    val xs = List(3, 1, 4, 1, 5, 9, 2, 6, 5, 3)
    println(xs.distinct)
    println(xs.sorted.reverse)
    println(xs.sortBy(x => (x % 3, x)))
    println(xs.sortWith(_ > _))
    println(xs.partition(_ % 2 == 0))
    println(xs.span(_ < 5))
    println(xs.splitAt(3))
    println(xs.sliding(3, 2).toList)
    println(xs.grouped(4).toList)
    println(xs.zipWithIndex.filter(_._2 % 3 == 0))
    println(xs.scanLeft(0)(_ + _))
    println(xs.scanRight(0)(_ + _))
    println(xs.foldRight("")((x, acc) => acc + x))
    println(s"${xs.reduceOption(_ max _)} ${List.empty[Int].reduceOption(_ + _)}")
    println(xs.collect { case x if x > 4 => x * 10 })
    println(xs.collectFirst { case x if x > 4 => s"first $x" })
    println(s"${xs.indexOf(5)} ${xs.lastIndexOf(5)} ${xs.indexWhere(_ > 4)} ${xs.indexOfSlice(List(1, 5))}")
    println(s"${xs.count(_ == 1)} ${xs.exists(_ > 8)} ${xs.forall(_ > 0)}")
    println(xs.patch(1, List(0, 0), 3))
    println(xs.updated(0, 100))
    println(List(1, 2).padTo(5, 0))
    println(s"${xs.diff(List(1, 5, 5))} ${xs.intersect(List(5, 1, 7))}")
    println(List(1, 2, 3).combinations(2).toList)
    println(List(1, 2, 3).permutations.toList)
    println(List(List(1, 2, 3), List(4, 5, 6)).transpose)
    println(List((1, "a"), (2, "b")).unzip)
    println(List((1, "a", true), (2, "b", false)).unzip3)
    println(xs.groupBy(_ % 3).toList.sortBy(_._1))
    println(xs.groupMap(_ % 2 == 0)(_ * 10).toList.sortBy(_._1))
    println(xs.groupMapReduce(identity)(_ => 1)(_ + _).toList.sorted)
    println(xs.partitionMap(x => if x % 2 == 0 then Left(x) else Right(x.toString)))
    println(s"${xs.minBy(-_)} ${xs.maxBy(_ % 5)} ${xs.maxOption} ${List.empty[Int].minOption}")
    println(s"${xs.sum} ${xs.product} ${List(1.5, 2.5).sum}")
    println(s"${xs.startsWith(List(3, 1))} ${xs.endsWith(List(5, 3))} ${xs.containsSlice(List(9, 2))}")
    println(xs.distinctBy(_ % 4))
    println(s"${xs.sameElements(xs.toVector)} ${xs == xs.toVector}")
    println(xs.mkString("<", "|", ">") + " " + xs.take(3).toString)
    println(xs.tails.take(3).toList)
    println(xs.inits.take(2).toList)
    println(xs.zip(xs.tail).map(_ - _))
    println(xs.zipAll(List("a"), 0, "z").take(3))
    println(xs.lazyZip(xs.reverse).map(_ * _))
    println(xs.corresponds(xs.map(_ * 2))(_ * 2 == _))
    println(xs.segmentLength(_ < 5))
    println(s"${xs.sorted.search(4)} ${xs.sorted.search(7)}")
    println(xs.find(_ > 100).isEmpty)
    println(xs.iterator.filter(_ > 3).map(_ + 1).toList)
    println(s"${xs.knownSize} ${Vector(1, 2).knownSize} ${xs.sizeCompare(10)} ${xs.lengthIs > 3}")
    println(xs.tapEach(_ => ()).headOption)
    println(xs.flatMap(x => if x > 4 then List(x, x) else Nil))
    println(xs.foldLeft(List.empty[Int])((acc, x) => x :: acc))
    println(xs.view.map(_ + 1).filter(_ % 2 == 0).toList)

  def vectors(): Unit =
    section("Vector")
    val v = (1 to 100).toVector
    println(s"${v.length} ${v(50)} ${v.updated(50, -1)(50)}")
    println((0 +: Vector(1, 2) :+ 3) ++ Vector(4))
    var big = Vector.empty[Int]
    for i <- 0 until 5000 do big = big :+ i
    println(s"${big.length} ${big(4321)} ${big.sum}")
    var prepended = Vector.empty[Int]
    for i <- 0 until 2000 do prepended = i +: prepended
    println(s"${prepended.take(3)} ${prepended.last}")
    println(s"${big.slice(1000, 1005)} ${big.drop(4998)} ${big.takeRight(1)}")
    println(Vector.fill(2, 3)(0))
    println(Vector.tabulate(2, 3)((i, j) => i * 3 + j))
    println(v.filter(_ % 25 == 0).reverse)
    println(Vector.from(Iterator(1, 2, 3)) == Vector(1, 2, 3))
    println(try Vector(1)(5) catch case e: IndexOutOfBoundsException => e.getClass.getName)

  def ranges(): Unit =
    section("Range")
    println(1 to 5)
    println(1 until 5)
    println((1 to 10 by 3).toList)
    println((10 to 1 by -2).toList)
    println(s"${(1 to 0).isEmpty} ${(1 to 0).toList}")
    println(s"${(1 to 100).sum} ${(1 to 100).length} ${(0 until 100 by 7).last}")
    println((1 to 10).reverse.take(3))
    println(s"${(1 to 10).contains(5)} ${(1 to 10 by 2).contains(4)}")
    println((1L to 5L).map(_ * 1000000000000L))
    println((1L to 10L by 4L).toList)
    println(Range.inclusive(0, 20, 5))
    println(Range(0, 10).splitAt(4))
    println((BigInt(1) to BigInt(3)).toList)
    println(BigDecimal("0.1").to(BigDecimal("0.5")).by(BigDecimal("0.2")).toList)
    println(('a' to 'e').mkString + " " + ('a' to 'z' by 5).toList)
    println(Range(Int.MaxValue - 2, Int.MaxValue).toList)
    println(try (Int.MinValue to Int.MaxValue).length catch case e: IllegalArgumentException => "too long")

  def sets(): Unit =
    section("Set")
    val s = Set(5, 1, 3)
    println(s + 2 - 5 + 1)
    println(s"${s.contains(3)} ${s(4)} ${s.size}")
    val big = (1 to 50).toSet
    println(s"${big.size} ${big.toList.sorted.take(5)} ${big.sum}")
    println(s"${(big & Set(10, 20, 60)).toList.sorted} ${(Set(1, 2, 3) | Set(3, 4)).toList.sorted}")
    println(s"${(Set(1, 2, 3) &~ Set(2)).toList.sorted} ${Set(1, 2).subsetOf(Set(1, 2, 3))}")
    println(HashSet("pear", "apple", "fig").map(_.length).toList.sorted)
    println(Set(1, 2, 3) == HashSet(3, 2, 1))
    println(Set(1, 2) == Set(2, 1))
    println(Set("a", "b").subsets().map(_.toList.sorted).toList.sortBy(_.mkString))
    println(ListSet(3, 1, 2) + 0)
    println(Set.empty[String].isEmpty)
    println((Set("b", "a") ++ List("c", "a")).toList.sorted)

  def maps(): Unit =
    section("Map")
    val m = Map("one" -> 1, "two" -> 2, "three" -> 3)
    println(m + ("four" -> 4) - "one")
    println(s"${m.get("two")} ${m.get("zero")} ${m.getOrElse("zero", 0)}")
    println(m.withDefaultValue(-1)("missing"))
    println(m.map((k, v) => v -> k).toList.sorted)
    println(m.view.mapValues(_ * 10).toList.sorted)
    println(m.view.filterKeys(_.startsWith("t")).toMap.toList.sorted)
    println(m.updated("two", 22)("two"))
    println(s"${m.updatedWith("two")(_.map(_ + 100))} ${m.updatedWith("ten")(_ => Some(10)).get("ten")}")
    println(m.removed("three").keySet.toList.sorted)
    println(m.foldLeft(0)(_ + _._2))
    println(s"${m.maxBy(_._2)} ${m.minBy(_._1)}")
    println(s"${m.keys.toList.sorted} ${m.values.toList.sorted}")
    println(m.collect { case (k, v) if v > 1 => k.toUpperCase }.toList.sorted)
    val big = (1 to 100).map(i => i -> i * i).toMap
    println(s"${big.size} ${big(77)} ${big.count(_._2 % 2 == 0)}")
    println((HashMap("a" -> 1) ++ HashMap("a" -> 2, "b" -> 3)).toList.sorted)
    println(HashMap("a" -> 1).merged(HashMap("a" -> 2))((x, y) => (x._1, x._2 + y._2)))
    println(m.toSeq.sortBy(_._2).map(_._1))
    println(Map(1 -> "a") == HashMap(1 -> "a"))
    println(m.transform((k, v) => k.length + v).toList.sorted)
    println(m.partition(_._2 > 1)._1.toList.sorted)
    println(m.concat(List("ten" -> 10)).size)
    println(try m("zero") catch case e: NoSuchElementException => e.getMessage)
    val lm = ListMap("z" -> 1, "a" -> 2, "m" -> 3)
    println(lm + ("b" -> 4))
    println(lm.updated("z", 9))
    val vm = VectorMap("z" -> 1, "a" -> 2, "m" -> 3)
    println(vm + ("b" -> 4) - "a")
    println(vm.updated("z", 9).keys.toList)
    println(SeqMap("y" -> 1, "x" -> 2))

  def sortedCollections(): Unit =
    section("SortedMap, SortedSet")
    val tm = TreeMap(5 -> "five", 1 -> "one", 3 -> "three", 9 -> "nine")
    println(tm)
    println(s"${tm.head} ${tm.last} ${tm.firstKey} ${tm.lastKey}")
    println(s"${tm.range(2, 9)} ${tm.rangeFrom(5)} ${tm.rangeTo(3)} ${tm.rangeUntil(3)}")
    println(s"${tm.minAfter(4)} ${tm.maxBefore(4)} ${tm.minAfter(10)}")
    println(tm.iteratorFrom(3).map(_._1).toList)
    println(tm.keysIteratorFrom(4).toList)
    println(tm + (2 -> "two") - 9)
    println(TreeMap("b" -> 1, "a" -> 2)(using Ordering[String].reverse))
    println(SortedMap(3 -> 'c', 1 -> 'a').map((k, v) => (k * 10, v)))
    val ts = TreeSet(5, 3, 8, 1, 9, 2)
    println(ts)
    println(s"${ts.range(2, 8)} ${ts.rangeFrom(5)} ${ts.rangeTo(3)}")
    println(s"${ts.minAfter(4)} ${ts.maxBefore(4)}")
    println(ts.iteratorFrom(5).toList)
    println(TreeSet("pear", "Apple", "fig")(using Ordering.by[String, String](_.toLowerCase)))
    println(TreeSet(3, 1, 2)(using Ordering.Int.reverse))
    println(SortedSet(1, 2, 3).map(-_))
    println(s"${(TreeSet.empty[Int] ++ (1 to 1000).reverse).take(5).toList} ${(1 to 1000).to(TreeSet).size}")
    println(ts.ordering.compare(1, 2))
    println(TreeSet(1, 2, 3).unsorted.toList.sorted)

  def queues(): Unit =
    section("Queue")
    val q = Queue(1, 2, 3)
    val (first, rest) = q.dequeue
    println(s"$first $rest")
    println(q.enqueue(4).enqueueAll(List(5, 6)))
    println(Queue.empty[Int].dequeueOption)
    println(s"${q.front} ${(q :+ 4).last}")
    var acc = Queue.empty[Int]
    for i <- 1 to 10 do acc = acc.enqueue(i)
    for _ <- 1 to 4 do acc = acc.dequeue._2
    println(s"$acc ${acc.length}")

  def arraySeqs(): Unit =
    section("ArraySeq")
    val a = ArraySeq(3, 1, 2)
    println(s"$a ${a.sorted} ${a.map(_ * 2)}")
    println(ArraySeq.unsafeWrapArray(Array("x", "y")) :+ "z")
    println(s"${a.updated(0, 9)} $a")
    println(ArraySeq.empty[Double] :+ 1.5)
    println(a.appendedAll(List(7, 8)).reverse)
    println(IndexedSeq(1, 2, 3).getClass.getSimpleName)
    println(Seq(1, 2, 3).getClass.getName)

  def bitSets(): Unit =
    section("BitSet")
    val b = BitSet(1, 5, 64, 200)
    println(b + 3 - 64)
    println(s"${b.contains(200)} ${b.contains(2)} ${b.size} ${b.max}")
    println(b | BitSet(2, 5) & BitSet(5, 6))
    println(b.toBitMask.toList)
    println(BitSet.fromBitMask(Array(5L, 1L)))
    println((b ^ BitSet(1, 2)).toList)
    println(b.map(_ * 2))
    println(b.rangeFrom(6))
