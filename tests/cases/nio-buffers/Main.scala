import java.nio.*
import java.nio.charset.*

/** java.nio buffers and the charset coders on buffers: states, exceptions, byte orders, views,
 *  comparisons and hash codes, checked against the JDK.
 */
object Main:
  def section(name: String): Unit = println(s"-- $name")

  def error(body: => Any): String =
    try s"ok ${body}"
    catch case e: Exception => s"${e.getClass.getName}: ${e.getMessage}"

  def state(b: Buffer): String = s"pos=${b.position()} lim=${b.limit()} cap=${b.capacity()} rem=${b.remaining()}"

  def byteBuffers(): Unit =
    section("ByteBuffer")
    val b = ByteBuffer.allocate(16)
    println(b)
    println(s"${b.order()} hasArray ${b.hasArray} direct ${b.isDirect} readOnly ${b.isReadOnly} offset ${b.arrayOffset()}")
    b.put(1.toByte).put(2.toByte).putShort(0x0304).putInt(0x05060708).putLong(0x090a0b0c0d0e0f10L)
    println(state(b))
    println(b.array().mkString(","))
    b.flip()
    println(s"${state(b)} get ${b.get()} short ${b.getShort(1)} int ${b.getInt(4)} long ${b.getLong(8)}")
    b.order(ByteOrder.LITTLE_ENDIAN)
    println(s"${b.order()} short ${b.getShort(2)} int ${b.getInt(4)} long ${b.getLong(8)} char ${b.getChar(0).toInt}")
    b.clear()
    b.putFloat(1.5f).putDouble(-2.25).putChar('é')
    println(s"${b.array().take(14).mkString(",")} float ${b.getFloat(0)} double ${b.getDouble(4)} char ${b.getChar(12)}")
    b.order(ByteOrder.BIG_ENDIAN)
    println(s"big-endian float ${b.getFloat(0)} double ${b.getDouble(4)}")

    section("positions")
    val c = ByteBuffer.wrap("hello, world".getBytes("UTF-8"), 3, 5)
    println(state(c))
    c.mark()
    val dst = new Array[Byte](3)
    c.get(dst)
    println(s"${new String(dst, "UTF-8")} ${state(c)}")
    c.reset()
    println(s"after reset ${state(c)}")
    c.position(6)
    println(s"position 6 ${state(c)} ${error(c.reset())}")
    c.limit(4)
    println(s"limit 4 ${state(c)}")
    c.rewind()
    println(s"rewind ${state(c)}")
    val s = c.slice()
    println(s"slice ${state(s)} first ${s.get(0).toChar} offset ${s.arrayOffset()}")
    val d = c.duplicate()
    d.position(2)
    println(s"duplicate ${state(d)} original ${state(c)}")
    val e = ByteBuffer.wrap("abcdef".getBytes("UTF-8"))
    e.position(2)
    e.compact()
    println(s"compact ${state(e)} ${new String(e.array(), "UTF-8")}")
    println(s"slice(1, 3) ${state(e.slice(1, 3))} ${e.slice(1, 3).get().toChar}")

    section("bulk")
    val src = ByteBuffer.wrap(Array[Byte](1, 2, 3, 4, 5, 6))
    val target = ByteBuffer.allocate(8)
    target.put(src)
    println(s"${state(src)} ${state(target)} ${target.array().mkString(",")}")
    target.put(0, Array[Byte](9, 9), 0, 2)
    target.put(5, ByteBuffer.wrap(Array[Byte](7, 7, 7)), 1, 2)
    println(target.array().mkString(","))
    val out = new Array[Byte](4)
    target.get(1, out)
    println(out.mkString(","))

    section("errors")
    val f = ByteBuffer.allocate(8)
    println(error(f.position(9)))
    println(error(f.position(-1)))
    println(error(f.limit(9)))
    println(error(f.get(8)))
    println(error(f.getInt(6)))
    println(error(f.getLong(1)))
    f.position(6)
    println(error(f.getInt()))
    println(error(f.putInt(1)))
    println(error(f.get(new Array[Byte](3))))
    println(error(f.get(new Array[Byte](3), 2, 2)))
    println(error(f.put(f)))
    println(error(f.slice(3, 9)))
    println(error(ByteBuffer.allocate(-1)))
    println(error(ByteBuffer.wrap(new Array[Byte](4), 3, 2)))
    val ro = f.asReadOnlyBuffer()
    println(s"$ro ${ro.isReadOnly} hasArray ${ro.hasArray}")
    println(error(ro.put(0.toByte)))
    println(error(ro.array()))
    println(error(ro.compact()))
    println(error(ro.putInt(0, 1)))

    section("comparisons")
    val x = ByteBuffer.wrap(Array[Byte](1, 2, 3))
    println(x.compareTo(ByteBuffer.wrap(Array[Byte](1, 7))))
    println(x.compareTo(ByteBuffer.wrap(Array[Byte](1))))
    println(x.equals(ByteBuffer.wrap(Array[Byte](0, 1, 2, 3)).position(1)))
    println(x.mismatch(ByteBuffer.wrap(Array[Byte](1, 2, 4))))
    println(x.mismatch(ByteBuffer.wrap(Array[Byte](1, 2, 3))))
    println(x.hashCode)
    println(ByteBuffer.wrap(Array[Byte](-1, 127, -128)).hashCode)
    println(ByteBuffer.allocate(4).equals(IntBuffer.allocate(1)))

  def views(): Unit =
    section("views")
    val b = ByteBuffer.allocate(16)
    val ints = b.asIntBuffer()
    println(ints)
    ints.put(1).put(-2).put(0x01020304)
    println(b.array().take(12).mkString(","))
    println(s"${ints.order()} ${ints.get(2)} hasArray ${ints.hasArray} ${error(ints.array())}")
    b.order(ByteOrder.LITTLE_ENDIAN)
    val little = b.asIntBuffer()
    println(s"$little ${little.order()} ${little.get(2)}")
    b.position(4)
    val longs = b.asLongBuffer()
    println(s"$longs ${longs.get(0)}")
    val ro = b.asReadOnlyBuffer().order(ByteOrder.LITTLE_ENDIAN).asShortBuffer()
    println(s"$ro ${error(ro.put(1.toShort))}")
    val chars = ByteBuffer.wrap("\u0000h\u0000i\u0000!".getBytes("ISO-8859-1")).asCharBuffer()
    println(s"${chars.getClass.getName} '$chars' ${chars.length()} ${chars.charAt(1)}")
    val doubles = ByteBuffer.allocate(16).asDoubleBuffer()
    doubles.put(Array(1.0, 0.1))
    doubles.flip()
    println(s"$doubles ${doubles.get()} ${doubles.get()} ${error(doubles.get())}")
    val floats = ByteBuffer.allocate(8).asFloatBuffer().put(2.5f).slice()
    println(s"$floats ${floats.put(0, 4.0f).get(0)}")

  def typedBuffers(): Unit =
    section("typed buffers")
    val i = IntBuffer.allocate(4)
    println(s"$i ${i.order() == ByteOrder.nativeOrder()} hasArray ${i.hasArray}")
    i.put(Array(3, 1, 4, 1), 1, 3)
    i.flip()
    println(s"${state(i)} ${i.get()} ${i.get(2)} ${error(i.get(3))}")
    val j = IntBuffer.wrap(Array(1, 2, 3))
    println(s"${j.compareTo(IntBuffer.wrap(Array(1, 7)))} ${j.compareTo(IntBuffer.wrap(Array(1, 2)))} ${j.hashCode}")
    val l = LongBuffer.wrap(Array(1L << 40, -1L))
    println(s"$l ${l.get(0)} ${l.hashCode} ${l.asReadOnlyBuffer()}")
    val sh = ShortBuffer.allocate(3).put(5.toShort).put((-6).toShort)
    sh.flip()
    println(s"${sh.get()} ${sh.slice()} ${sh.compareTo(ShortBuffer.wrap(Array[Short](-7)))}")
    println(FloatBuffer.wrap(Array(0f)).equals(FloatBuffer.wrap(Array(-0f))))
    println(FloatBuffer.wrap(Array(Float.NaN)).equals(FloatBuffer.wrap(Array(Float.NaN))))
    println(FloatBuffer.wrap(Array(0f, 1f)).compareTo(FloatBuffer.wrap(Array(-0f, 2f))))
    println(FloatBuffer.wrap(Array(0f)).mismatch(FloatBuffer.wrap(Array(-0f))))
    println(DoubleBuffer.wrap(Array(1.5, 2.5)).hashCode)
    println(DoubleBuffer.wrap(Array(Double.NaN, 1.0)).compareTo(DoubleBuffer.wrap(Array(2.0, 1.0))))
    val ro = DoubleBuffer.wrap(Array(1.0)).asReadOnlyBuffer()
    println(s"$ro ${error(ro.array())} ${error(ro.put(2.0))}")
    println(error(IntBuffer.allocate(-1)))

  def charBuffers(): Unit =
    section("CharBuffer")
    val c = CharBuffer.allocate(8)
    c.put("héllo").append(", ").append('w')
    println(s"${state(c)} ${error(c.append("orld"))}")
    c.flip()
    println(s"'$c' length ${c.length()} charAt(1) ${c.charAt(1)} ${error(c.charAt(8))}")
    val sub = c.subSequence(1, 4)
    println(s"subSequence '$sub' ${state(sub)}")
    println(s"${c.getClass.getName} ${c.hashCode} ${c.equals(CharBuffer.wrap("héllo, w"))}")
    val w = CharBuffer.wrap("abcdef", 1, 4)
    println(s"${w.getClass.getName} '$w' ${state(w)} readOnly ${w.isReadOnly} ${error(w.put('x'))} ${error(w.array())}")
    println(s"chars ${w.chars().toArray.mkString(",")} slice '${w.slice()}' get ${w.get()} '$w'")
    println(s"isEmpty ${CharBuffer.allocate(0).isEmpty} compare ${CharBuffer.wrap("abc").compareTo(CharBuffer.wrap("abd"))}")
    println(error(CharBuffer.allocate(2).put("abc")))
    println(error(CharBuffer.wrap("abc").subSequence(2, 1)))
    val reader = new java.io.StringReader("read through a CharBuffer")
    val target = CharBuffer.allocate(10)
    println(s"read ${reader.read(target)} '${target.flip()}'")
    val from = CharBuffer.wrap("readable")
    val to = CharBuffer.allocate(4)
    println(s"Readable ${from.read(to)} '${to.flip()}' '$from'")
    val sb = new java.lang.StringBuilder()
    sb.append(CharBuffer.wrap("into a StringBuilder"))
    println(sb)
    println(String.join("+", CharBuffer.wrap("a"), CharBuffer.wrap(Array('b', 'c'))))

  def coders(): Unit =
    section("charsets")
    val utf8 = StandardCharsets.UTF_8
    val bytes = utf8.encode("Grüße, 世界 😀")
    println(s"pos=${bytes.position()} lim=${bytes.limit()} ${bytes.array().take(bytes.limit()).mkString(",")}")
    val chars = utf8.decode(bytes)
    println(s"'$chars' ${bytes.remaining()}")
    println(s"'${utf8.decode(ByteBuffer.wrap(Array[Byte]('a', -1, 'b')))}'")
    println(s"latin1 ${StandardCharsets.ISO_8859_1.encode("é€").array().take(2).mkString(",")}")

    val decoder = utf8.newDecoder()
    println(error(decoder.decode(ByteBuffer.wrap(Array[Byte]('a', -1, 'b')))))
    val in = ByteBuffer.wrap("añb".getBytes("UTF-8"))
    val out = CharBuffer.allocate(10)
    in.limit(2) // splits ñ
    val r1 = decoder.reset().decode(in, out, false)
    println(s"$r1 ${state(in)} ${state(out)}")
    in.limit(4)
    val r2 = decoder.decode(in, out, true)
    println(s"$r2 ${state(in)} '${out.duplicate().flip()}' flush ${decoder.flush(out)}")
    println(error(decoder.decode(in, out, false)))
    val small = CharBuffer.allocate(1)
    val r3 = decoder.reset().decode(ByteBuffer.wrap("xy".getBytes("UTF-8")), small, true)
    println(s"$r3 overflow ${r3.isOverflow} ${error(r3.length())}")
    val bad = ByteBuffer.wrap(Array[Byte]('x', -61, 'y'))
    val r4 = decoder.reset().decode(bad, CharBuffer.allocate(10), true)
    println(s"$r4 malformed ${r4.isMalformed} length ${r4.length()} ${state(bad)} ${error(r4.throwException())}")

    val encoder = StandardCharsets.US_ASCII.newEncoder()
    println(s"canEncode ${encoder.canEncode('a')} ${encoder.canEncode('é')} ${encoder.canEncode("abc")}")
    println(error(encoder.encode(CharBuffer.wrap("café"))))
    val buf = ByteBuffer.allocate(10)
    val r5 = encoder.reset().encode(CharBuffer.wrap("café"), buf, true)
    println(s"$r5 unmappable ${r5.isUnmappable} ${state(buf)}")
    encoder.onUnmappableCharacter(CodingErrorAction.REPLACE).replaceWith(Array[Byte]('*'))
    val replaced = encoder.encode(CharBuffer.wrap("café"))
    println(s"${new String(replaced.array(), 0, replaced.limit(), "US-ASCII")} ${error(encoder.replaceWith(Array[Byte](-1)))}")
    println(s"${CoderResult.malformedForLength(2)} ${CoderResult.unmappableForLength(1)} ${CoderResult.UNDERFLOW}")

  def main(args: Array[String]): Unit =
    byteBuffers()
    views()
    typedBuffers()
    charBuffers()
    coders()
