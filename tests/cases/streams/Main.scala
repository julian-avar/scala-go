    log.clear()
    show(IntStream.range(0, 1000000).peek(i => log.add(s"$i")).anyMatch(_ == 2), log)
    log.clear()
    show(Stream.of(List("a", "b", "c"), List("d")).flatMap(l => l.asJava.stream().peek(x => log.add(x))).findFirst(), log)
    log.clear()
    show(IntStream.range(0, 10).peek(i => log.add(s"$i")).sorted().findFirst(), log.size())
    log.clear()
    show(IntStream.of(3, 1, 2).peek(i => log.add(s"$i")).sorted().peek(i => log.add(s"s$i")).boxed().toList, log)
    log.clear()
    val iter = Stream.of("a", "b", "c").peek(x => log.add(x)).iterator()
    println(s"${iter.next()} $log")
    println(s"${iter.next()} ${iter.hasNext} $log")
    log.clear()
    val inner = Stream.of(1, 2).flatMap(i => Stream.of(i, i * 10).onClose(() => log.add(s"closed $i"))).iterator()
    println(s"${iter.next()} ${inner.next()} $log")
    println(s"${inner.next()} ${inner.next()} $log")
    // Pulling from infinite and stateful pipelines.
    println(Stream.iterate(1, (i: Int) => i + 1).filter(_ % 2 == 0).limit(3).iterator().asScala.toList)
    val sortedIt = IntStream.of(3, 1, 2).sorted().iterator()
