  def closing(): Unit =
    section("closing")
    val log = new ju.ArrayList[String]()
    val s = Stream.of(1, 2, 3).onClose(() => log.add("first")).map(_ * 2).onClose(() => log.add("second"))
    show(s.toList, log)
    s.close()
    println(log)
    s.close()
    println(log)
    log.clear()
    val failing = Stream.of(1).onClose(() => throw new IllegalStateException("one")).onClose(() => throw new IllegalArgumentException("two"))
    try failing.close()
    catch case e: Exception => println(s"${e.getMessage} suppressed ${e.getSuppressed.map(_.getMessage).toList}")
    val a = Stream.of("a").onClose(() => log.add("close a"))
    val b = Stream.of("b").onClose(() => log.add("close b"))
    val c = Stream.concat(a, b)
    show(c.toList, log)
    c.close()
    println(log)
    log.clear()
    show(Stream.of(1, 2).flatMap(i => Stream.of(i).onClose(() => log.add(s"inner $i"))).map(_ + 1).toList, log)
    log.clear()
    val tryWith = scala.util.Using.resource(IntStream.range(0, 3).onClose(() => log.add("using")))(_.sum())
    println(s"$tryWith $log")

